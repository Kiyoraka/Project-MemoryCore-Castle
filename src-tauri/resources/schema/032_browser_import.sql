CREATE TABLE browser_vault (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 host VARCHAR(253) NOT NULL,
 username VARCHAR(320) NOT NULL DEFAULT '',
 secret VARBINARY(2048) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY ux_browser_vault (host, username)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE browser_bookmarks (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 title VARCHAR(200) NOT NULL DEFAULT '',
 url VARCHAR(1000) NOT NULL,
 url_hash CHAR(64) NOT NULL,
 folder VARCHAR(300) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY ux_browser_bookmarks (url_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
