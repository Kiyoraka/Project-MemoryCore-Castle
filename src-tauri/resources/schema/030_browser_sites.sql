CREATE TABLE browser_visits (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 host VARCHAR(253) NOT NULL,
 path VARCHAR(512) NOT NULL DEFAULT '/',
 title VARCHAR(120) NOT NULL DEFAULT '',
 first_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 last_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 count INT UNSIGNED NOT NULL DEFAULT 1,
 has_login TINYINT(1) NOT NULL DEFAULT 0,
 mark_id INT UNSIGNED NULL,
 UNIQUE KEY ux_browser_visits (host, path),
 KEY ix_browser_visits_mark (mark_id),
 KEY ix_browser_visits_last (last_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE sentinel_site_marks (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 host VARCHAR(253) NOT NULL,
 verdict VARCHAR(12) NOT NULL,
 reason VARCHAR(300) NOT NULL DEFAULT '',
 marked_by VARCHAR(8) NOT NULL DEFAULT 'sentinel',
 marked_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 pattern_id INT UNSIGNED NULL,
 UNIQUE KEY ux_sentinel_site_marks (host)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE sentinel_site_patterns (
 id INT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 kind VARCHAR(12) NOT NULL,
 value VARCHAR(253) NOT NULL,
 verdict VARCHAR(12) NOT NULL,
 why VARCHAR(300) NOT NULL DEFAULT '',
 learned_from VARCHAR(253) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 active TINYINT(1) NOT NULL DEFAULT 1,
 UNIQUE KEY ux_sentinel_site_patterns (kind, value)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
