/// The `Grapheme_Cluster_Break` property (UAX #29). `Extended_Pictographic` is separate:
/// [`is_extended_pictographic`].
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum GraphemeBreak {
    Other,
    CR,
    LF,
    Control,
    Extend,
    ZWJ,
    RegionalIndicator,
    Prepend,
    SpacingMark,
    /// Hangul leading jamo.
    L,
    /// Hangul vowel jamo.
    V,
    /// Hangul trailing jamo.
    T,
    /// Hangul syllable without a trailing consonant.
    LV,
    /// Hangul syllable with a trailing consonant.
    LVT,
}

const HANGUL_FIRST: u32 = 0xAC00;
const HANGUL_LAST: u32 = 0xD7A3;

/// The grapheme cluster break class of a character.
pub fn grapheme_break(c: char) -> GraphemeBreak {
    let cp = c as u32;
    if (HANGUL_FIRST..=HANGUL_LAST).contains(&cp) {
        return if (cp - HANGUL_FIRST) % 28 == 0 { GraphemeBreak::LV } else { GraphemeBreak::LVT };
    }
    find(gcb::TABLE, cp).unwrap_or(GraphemeBreak::Other)
}

