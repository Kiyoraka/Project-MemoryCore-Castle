/// A coarse General Category: the first letter of the Unicode category, with Z split off.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Category {
    /// L*
    Letter,
    /// M*
    Mark,
    /// N*
    Number,
    /// P*
    Punctuation,
    /// S*
    Symbol,
    /// Z* (space, line and paragraph separators)
    Separator,
    /// Cc
    Control,
    /// Cf, Co, Cn
    Other,
}

/// The coarse category of a character, from the standard library's Unicode predicates and the
/// tables above. Letter/Number come straight from `char::is_alphabetic`/`is_numeric`; the
/// punctuation/symbol split follows the line break class (good for Latin, CJK and general
/// punctuation; approximate for rare symbols).
pub fn coarse_category(c: char) -> Category {
    if c.is_control() {
        return Category::Control;
    }
    let cp = c as u32;
    if (0x1F3FB..=0x1F3FF).contains(&cp) {
        return Category::Symbol;
    }
    match grapheme_break(c) {
        GraphemeBreak::Extend | GraphemeBreak::SpacingMark if cp != 0x200C && !(0xE0020..=0xE007F).contains(&cp) => {
            if (0xFF9E..=0xFF9F).contains(&cp) {
                return Category::Letter;
            }
            return Category::Mark;
        }
        GraphemeBreak::Control | GraphemeBreak::ZWJ | GraphemeBreak::Prepend if !c.is_alphabetic() => {
            return if c.is_whitespace() { Category::Separator } else { Category::Other };
        }
        _ => {}
    }
    if (0x200C..=0x200D).contains(&cp) || (0xE0020..=0xE007F).contains(&cp) || is_default_ignorable(c) {
        return Category::Other;
    }
    if c.is_whitespace() {
        return Category::Separator;
    }
    if (0xE000..=0xF8FF).contains(&cp) || cp >= 0xF0000 {
        return Category::Other;
    }
    if c.is_numeric() {
        return Category::Number;
    }
    if c.is_alphabetic() {
        return Category::Letter;
    }
    use LineBreak::*;
    match line_break(c) {
        OP | CL | CP | QU | EX | IS | HY | BA | BB | B2 | NS | IN | GL => Category::Punctuation,
        SY if c == '/' => Category::Punctuation,
        _ if matches!(c, '#' | '%' | '&' | '*' | '@' | '\\' | '_' | '\u{00A1}' | '\u{00A7}' | '\u{00B6}' | '\u{00B7}' | '\u{00BF}') => {
            Category::Punctuation
        }
        _ => Category::Symbol,
    }
}

/// True for characters laid out as ideographic cells (CJK ideographs, kana, Hangul, fullwidth
/// forms, CJK punctuation): the ones Distribute/Justify may space apart.
pub fn is_cjk(c: char) -> bool {
    use LineBreak::*;
    if matches!(line_break(c), ID | CJ | H2 | H3 | JL | JV | JT) && !is_extended_pictographic(c) {
        return true;
    }
    let cp = c as u32;
    matches!(east_asian_width(c), EastAsianWidth::W | EastAsianWidth::F) && !is_extended_pictographic(c) && cp >= 0x2E80
}

#[cfg(test)]
pub(super) fn all_tables_sorted() -> Result<(), String> {
    fn check<T>(name: &str, t: &[(u32, u32, T)]) -> Result<(), String> {
        for (i, w) in t.iter().enumerate() {
            if w.0 > w.1 {
                return Err(format!("{name}[{i}] {:X}..{:X} is reversed", w.0, w.1));
            }
            if i > 0 && t[i - 1].1 >= w.0 {
                return Err(format!("{name}[{i}] {:X} overlaps or precedes {:X}", w.0, t[i - 1].1));
            }
        }
        Ok(())
    }
    fn check2(name: &str, t: &[(u32, u32)]) -> Result<(), String> {
        let v: Vec<(u32, u32, ())> = t.iter().map(|&(a, b)| (a, b, ())).collect();
        check(name, &v)
    }
    check("gcb", gcb::TABLE)?;
    check("lb", lbt::TABLE)?;
    check("eaw", eaw::TABLE)?;
    check2("ext_pict", EXT_PICT)?;
    check2("default_ignorable", DEFAULT_IGNORABLE)?;
    Ok(())
}
