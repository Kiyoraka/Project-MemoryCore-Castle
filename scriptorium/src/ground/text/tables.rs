//! Unicode property tables, written by hand (no UCD download, no generator): the UAX #29 grapheme
//! cluster break property, `Extended_Pictographic`, the UAX #14 line break classes, East Asian
//! Width, and a coarse General Category derived from them plus the standard library's own
//! Unicode predicates (`char::is_alphabetic`, `is_numeric`, `is_whitespace`, `is_control`).
//!
//! Format: sorted, non-overlapping `(first, last, value)` arrays searched by binary search. A test
//! (`tables_are_sorted`) checks every table's order.
//!
//! Based on Unicode 15.0 as remembered, not copied. Coverage, honestly:
//! - Complete for what Scriptorium writes first: ASCII, Latin-1, Latin Extended, Greek, Cyrillic,
//!   general and supplemental punctuation, currency, CJK symbols, Hiragana, Katakana (incl. small
//!   kana and halfwidth forms), CJK Unified Ideographs (+ Ext A and the supplementary planes, by
//!   range), Hangul jamo (L/V/T, incl. Jamo Extended A/B) and syllables (LV/LVT computed), fullwidth
//!   forms, combining marks (Mn/Me/Mc of the BMP Indic and South-East Asian scripts), emoji
//!   (Extended_Pictographic, regional indicators, skin-tone modifiers, ZWJ) and the line break classes
//!   of the emoji blocks (ID/EB/EM).
//! - Approximate: rarely used symbols (arrows, math, dingbats) and supplementary-plane historic
//!   scripts. Their letters fall to AL (the UAX #14 default for unknowns), their marks to CM through
//!   the grapheme table, which lists the common supplementary Brahmic marks but not all of them.
//! - Not modelled: Unicode 15.1 additions (GB9c Indic conjunct breaks, the AK/AP/AS/VI/VF line break
//!   classes, LB15a-d quotation refinements, LB28a), and unassigned code points (treated as their
//!   block's default rather than XX).

use std::cmp::Ordering;

// ---------------------------------------------------------------------------------------------------
// Lookup
// ---------------------------------------------------------------------------------------------------

fn find<T: Copy>(table: &[(u32, u32, T)], cp: u32) -> Option<T> {
    let i = table.partition_point(|&(_, last, _)| last < cp);
    match table.get(i) {
        Some(&(first, last, v)) if first <= cp && cp <= last => Some(v),
        _ => None,
    }
}

fn contains(table: &[(u32, u32)], cp: u32) -> bool {
    table
        .binary_search_by(|&(first, last)| {
            if last < cp {
                Ordering::Less
            } else if first > cp {
                Ordering::Greater
            } else {
                Ordering::Equal
            }
        })
        .is_ok()
}

