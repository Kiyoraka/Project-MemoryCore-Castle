/// The `Line_Break` property (UAX #14), before the LB1 resolution of AI, CJ, SA, SG and XX (see
/// `segment.rs`).
#[allow(clippy::upper_case_acronyms)]
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum LineBreak {
    /// Mandatory break (FF, VT, LINE/PARAGRAPH SEPARATOR).
    BK,
    CR,
    LF,
    /// Next line (U+0085).
    NL,
    SP,
    /// Zero width space.
    ZW,
    ZWJ,
    /// Combining mark.
    CM,
    /// Word joiner.
    WJ,
    /// Non-breaking ("glue").
    GL,
    /// Break after.
    BA,
    /// Break before.
    BB,
    /// Break on either side, but not between two (em dash).
    B2,
    HY,
    /// Contingent break (object replacement).
    CB,
    /// Close punctuation.
    CL,
    /// Close parenthesis.
    CP,
    /// Exclamation / interrogation.
    EX,
    /// Inseparable (leaders).
    IN,
    /// Non-starter.
    NS,
    /// Open punctuation.
    OP,
    /// Quotation.
    QU,
    /// Infix numeric separator.
    IS,
    NU,
    /// Postfix numeric.
    PO,
    /// Prefix numeric.
    PR,
    /// Symbols allowing break after (solidus).
    SY,
    /// Alphabetic.
    AL,
    /// Hebrew letter.
    HL,
    /// Hangul LV syllable.
    H2,
    /// Hangul LVT syllable.
    H3,
    JL,
    JV,
    JT,
    /// Ideographic.
    ID,
    /// Conditional Japanese starter (small kana).
    CJ,
    RI,
    /// Emoji base.
    EB,
    /// Emoji modifier.
    EM,
    /// Ambiguous (alphabetic or ideographic by context).
    AI,
    /// South-East Asian complex context.
    SA,
    /// Unknown.
    XX,
}

/// The line break class of a character (unresolved: AI, CJ and SA are returned as such).
pub fn line_break(c: char) -> LineBreak {
    let cp = c as u32;
    if (HANGUL_FIRST..=HANGUL_LAST).contains(&cp) {
        return if (cp - HANGUL_FIRST) % 28 == 0 { LineBreak::H2 } else { LineBreak::H3 };
    }
    if let Some(v) = find(lbt::TABLE, cp) {
        return v;
    }
    // Marks and format controls not listed above are combining marks for line breaking.
    match grapheme_break(c) {
        GraphemeBreak::Extend | GraphemeBreak::SpacingMark | GraphemeBreak::Control => return LineBreak::CM,
        _ => {}
    }
    match cp {
        0x3400..=0x4DBF | 0x4E00..=0x9FFF | 0xF900..=0xFAFF | 0x20000..=0x2FFFD | 0x30000..=0x3FFFD => LineBreak::ID,
        0x17000..=0x18CFF | 0x1B000..=0x1B2FF => LineBreak::ID,
        0x1F000..=0x1FAFF | 0x1FC00..=0x1FFFD => LineBreak::ID,
        _ => LineBreak::AL,
    }
}

